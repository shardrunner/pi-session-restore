"""Isolated real-Pi integration checks. No desktop windows or provider credentials.

The fake terminal executes the exact argv generated by /restore in a fresh PTY.
Only standard-library Python modules are required (Linux).
"""
import json
import os
from pathlib import Path
import pty
import select
import signal
import subprocess
import sys
import tempfile
import time
import uuid

SOURCE = Path(__file__).resolve().parent
TIMEOUT = 20


def read_json(path):
    return json.loads(path.read_text())


def wait_for(predicate, process=None, timeout=TIMEOUT):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if process:
            process.drain()
        if predicate():
            return
        if process and process.proc.poll() is not None:
            raise AssertionError(f"Pi exited unexpectedly:\n{process.output.decode(errors='replace')[-12000:]}")
        time.sleep(0.05)
    output = process.output.decode(errors="replace")[-12000:] if process else ""
    raise AssertionError(f"Timed out waiting for integration condition:\n{output}")


class TerminalProcess:
    def __init__(self, argv, cwd, env):
        self.master, slave = pty.openpty()
        self.output = b""
        try:
            self.proc = subprocess.Popen(argv, stdin=slave, stdout=slave, stderr=slave,
                                         cwd=cwd, env=env, start_new_session=True)
        except BaseException:
            os.close(self.master)
            raise
        finally:
            os.close(slave)

    def drain(self):
        if select.select([self.master], [], [], 0.02)[0]:
            try:
                self.output = (self.output + os.read(self.master, 65536))[-200000:]
            except OSError:
                pass  # Linux PTYs return EIO after the child closes.

    def send(self, text):
        os.write(self.master, text.encode())

    def close(self):
        if self.proc.poll() is None:
            os.killpg(self.proc.pid, signal.SIGTERM)
            try:
                self.proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                os.killpg(self.proc.pid, signal.SIGKILL)
                self.proc.wait()
        os.close(self.master)


def fake_terminal(root, argv):
    """Called by the real extension as its terminal command prefix."""
    root = Path(root)
    (root / "terminal-argv.json").write_text(json.dumps(argv))
    child = TerminalProcess(argv, root, os.environ.copy())
    try:
        deadline = time.monotonic() + 40
        rearmed = False
        while time.monotonic() < deadline and not (root / "stop-terminal").exists():
            child.drain()
            if not rearmed and (root / "rearm-child").exists() and b"Historical response" in child.output:
                child.send('/save "Rearmed"\r')
                rearmed = True
            if child.proc.poll() is not None:
                break
    finally:
        child.close()
        (root / "terminal-output.txt").write_bytes(child.output)
        (root / "terminal-closed").touch()


def environment(root):
    # Allowlist rather than copying os.environ: no API keys, auth paths, NODE_OPTIONS,
    # shell startup hooks, or parent-session variables reach the test process.
    return {"PATH": os.environ["PATH"], "HOME": str(root),
            "PI_CODING_AGENT_DIR": str(root), "PI_OFFLINE": "1",
            "PI_TELEMETRY": "0", "TERM": "xterm-256color", "LANG": "C.UTF-8"}


def session_file(root, name):
    path = root / "sessions" / "integration" / f"{name} $(literal) conversation.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    session_id = str(uuid.uuid4())
    stamp = "2026-01-01T00:00:00Z"
    entries = [
        {"type": "session", "version": 3, "id": session_id, "timestamp": stamp, "cwd": str(root)},
        {"type": "message", "id": "abc12345", "parentId": None, "timestamp": stamp,
         "message": {"role": "user", "content": "Historical test message", "timestamp": 1}},
        {"type": "message", "id": "def12345", "parentId": "abc12345", "timestamp": stamp,
         "message": {"role": "assistant", "content": [{"type": "text", "text": "Historical response"}],
                     "api": "openai-completions", "provider": "test", "model": "test",
                     "usage": {"input": 0, "output": 0, "cacheRead": 0, "cacheWrite": 0,
                               "totalTokens": 0, "cost": {"input": 0, "output": 0, "cacheRead": 0,
                                                         "cacheWrite": 0, "total": 0}},
                     "stopReason": "stop", "timestamp": 2}},
    ]
    path.write_text("".join(json.dumps(entry) + "\n" for entry in entries))
    return path, session_id


def setup(root):
    # Exercise the supported global package installation configuration, not -e.
    (root / "settings.json").write_text(json.dumps({"packages": [str(SOURCE)]}))
    (root / "session-restore").mkdir()


def pi_process(root, session, ticket=None):
    argv = ["pi", "--offline", "--no-context-files", "--no-skills", "--no-prompt-templates",
            "--session", str(session)]
    if ticket:
        argv += ["--saved-session-ticket", ticket]
    return TerminalProcess(argv, root, environment(root))


def state_path(root):
    return root / "session-restore" / "saved.json"


def entry(root):
    return read_json(state_path(root))["sessions"][0]


def successful_restore(root):
    setup(root)
    target, target_id = session_file(root, "target")
    source, _ = session_file(root, "source")
    # Save through the real command first; the notification is an explicit readiness
    # signal before later commands. No fixed startup sleeps.
    original = pi_process(root, target)
    try:
        wait_for(lambda: b"Historical response" in original.output, original)
        original.send('/save "Integration label"\r')
        wait_for(lambda: original.proc.poll() is not None, original)
        assert original.proc.returncode == 0
        assert entry(root)["label"] == "Integration label"
    finally:
        original.close()
    saved = read_json(state_path(root))
    saved["terminal"] = [sys.executable, str(SOURCE / "smoke-test.py"), "--terminal", str(root)]
    state_path(root).write_text(json.dumps(saved))
    parent = pi_process(root, source)
    launched = False
    try:
        wait_for(lambda: b"Historical response" in parent.output, parent)
        parent.send('/restore\r')
        wait_for(lambda: b"Restore all pending" in parent.output, parent)
        parent.send('\r')
        launched = True
        wait_for(lambda: entry(root)["status"] == "restored", parent)
        args = read_json(root / "terminal-argv.json")
        assert args[:6] == ["env", "--chdir", str(root), f"PI_CODING_AGENT_DIR={root}", "pi", "--session"], args
        assert args[6] == str(target), args
        assert args[7] == "--saved-session-ticket" and args[8], args
        assert entry(root)["sessionId"] == target_id
        (root / "rearm-child").touch()
        wait_for(lambda: entry(root)["status"] == "pending" and entry(root)["label"] == "Rearmed", parent)
        wait_for(lambda: (root / "terminal-closed").exists(), parent)
        assert len(read_json(state_path(root))["sessions"]) == 1
        print("PASS: global package discovery, /save exits → /restore → acknowledgement → resave replaces and exits")
    finally:
        parent.close()
        (root / "stop-terminal").touch()
        if launched:
            wait_for(lambda: (root / "terminal-closed").exists(), timeout=45)


def rejected_ticket(root, wrong_session):
    setup(root)
    target, target_id = session_file(root, "target")
    other, _ = session_file(root, "other")
    state_path(root).write_text(json.dumps({"version": 1, "sessions": [{
        "sessionId": target_id, "sessionFile": str(target), "cwd": str(root), "label": "Rejected",
        "status": "launching", "savedAt": "2026-01-01T00:00:00Z",
        "launchedAt": "2026-01-01T00:00:00Z", "ticket": "valid-ticket",
    }]}))
    before = target.read_bytes()
    child = pi_process(root, other if wrong_session else target,
                       "valid-ticket" if wrong_session else "expired-ticket")
    try:
        wait_for(lambda: child.proc.poll() is not None, child)
        assert entry(root)["status"] == "launching"
        # Pi can persist startup metadata before session_start reaches extensions.
        # Rejection guarantees exit, not a byte-for-byte read-only open.
        after_entries = [json.loads(line) for line in target.read_text().splitlines()]
        before_entries = [json.loads(line) for line in before.decode().splitlines()]
        assert [e for e in after_entries if e['type'] == 'message'] == [
            e for e in before_entries if e['type'] == 'message']
        assert after_entries[0] == before_entries[0]
        print(f"PASS: real Pi exits on {'wrong-session' if wrong_session else 'expired'} ticket without consuming the entry")
    finally:
        child.close()


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--terminal":
        fake_terminal(sys.argv[2], sys.argv[3:])
        return
    for scenario in [successful_restore,
                     lambda root: rejected_ticket(root, False),
                     lambda root: rejected_ticket(root, True)]:
        with tempfile.TemporaryDirectory(prefix="pi-restore-integration-") as root:
            scenario(Path(root))


if __name__ == "__main__":
    main()
